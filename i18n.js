function currentFleetLang() { return (window.CarinoLang && window.CarinoLang.current) || 'en'; }

function t(key) {
    const dict = I18N[currentFleetLang()];
    return (dict && dict[key]) || key;
}

// Static markup: elements carrying data-i18n use their original English text
// as the key (captured on first pass, whitespace-normalized; locale switches
// stay reversible). Script code that relabels an element sets
// dataset.i18nKey itself, so a later pass keeps the current label.
function applyStaticI18n() {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
        if (!el.dataset.i18nKey) el.dataset.i18nKey = el.textContent.trim().replace(/\s+/g, ' ');
        el.textContent = t(el.dataset.i18nKey);
    });
}

// Attributes: data-i18n-aria-label / -placeholder / -title hold the English
// key; the translation goes into the real attribute.
const I18N_ATTRS = [['i18nAriaLabel', 'aria-label'], ['i18nPlaceholder', 'placeholder'], ['i18nTitle', 'title']];
function applyAttrI18n() {
    I18N_ATTRS.forEach(([key, attr]) => {
        document.querySelectorAll('[data-i18n-' + attr + ']').forEach((el) => {
            el.setAttribute(attr, t(el.dataset[key]));
        });
    });
}

function applyI18n() {
    document.documentElement.lang = currentFleetLang();
    applyStaticI18n();
    applyAttrI18n();
    if (typeof repaintTp === 'function') repaintTp();   // the sample script, the readouts
}

document.addEventListener('DOMContentLoaded', applyI18n);
window.addEventListener('carino:langchange', applyI18n);
